def _suite(case):
    from qwen35_moe_dflash.op_probe_gdn_accuracy import cases_from_prepared
    return cases_from_prepared(case["prepared"], case["reference_path"], case["omc"])


def _weights(case):
    return {key: np.fromfile(case["prepared"] / item["path"], dtype="<f2").reshape(item["shape"])
            for key, item in case["plan"]["weights"].items()}


def _feeds():
    ids, mask = np.zeros((1, 8), np.int32), np.zeros((1, 8), np.int32)
    ids[0, :3], mask[0, :3] = [1, 2, 3], 1
    return {"input_ids": ids, "attention_mask": mask}


def _outputs(item):
    return dict(zip(item["output_labels"], item["expected"]))


def _same_half(actual, expected):
    assert actual.dtype == expected.dtype == np.float16
    np.testing.assert_array_equal(actual.view(np.uint16), expected.view(np.uint16))


def _full_target_stages(graph):
    # Resolve production graph values by named parameter edges. Autogenerated
    # v names differ because the complete target builds RoPE before layer 0.
    nodes = {node.output.name: node for node in graph.nodes}

    def with_weight(key):
        matches = [node for node in graph.nodes if graph.weights[key] in node.inputs]
        assert len(matches) == 1
        return matches[0]

    prefix = "target.layers.0.linear_attn."
    projection = with_weight(prefix + "out_proj.weight")
    gated = nodes[projection.inputs[0].name].inputs[0]
    weighted_norm = with_weight(prefix + "norm.weight")
    normalized = nodes[weighted_norm.inputs[0].name]
    gain = next(nodes[v.name] for v in normalized.inputs if nodes[v.name].kind == "rsqrt")
    core = next(v for v in normalized.inputs if v != gain.output)
    return {"layer0_final": nodes[graph.outputs[1].name].inputs[0],
            "input_norm": with_weight(prefix + "in_proj_qkv.weight").inputs[0],
            "chunk_core": core, "norm_input": gain.inputs[0], "norm_gain": gain.output,
            "gated_core": gated, "attention_branch": projection.output}


def test_first_layer_matches_original_full_target_and_does_not_regenerate_weights(case, monkeypatch):
    def no_regeneration(*args, **kwargs):
        raise AssertionError("diagnostics must read supplied prepared payloads")
    monkeypatch.setattr("qwen35_moe_dflash.ge_weights.tiny_weights", no_regeneration)
    before = pickle.dumps(case["graphs"])
    suite, provenance = _suite(case)
    assert [item["name"] for item in suite] == ["gdn_layer0_final", "gdn_layer0_stages", "gdn_layer0_rsqrt"]
    assert provenance["source"] == case["plan"]["source"]
    assert case["plan"]["source"]["fp16_payload_sha256"] == weight_identity(case["plan"]["weights"])
    assert provenance["bindings"] == {
        "prepared_manifest_sha256": sha256_file(case["prepared"] / "prepared.json"),
        "reference_sha256": sha256_file(case["reference_path"]),
        "omc_manifest_sha256": sha256_file(case["omc"] / "manifest.json")}
    assert len(provenance["selected_weights"]) == 19
    assert provenance["selected_weights"] == {
        key: case["plan"]["weights"][key] for key in suite[0]["weights"]}
    supplied_weights = _weights(case)
    full_top1, full_features = evaluate(case["graphs"][0], _feeds(), supplied_weights)
    assert full_top1[0, :3].tolist() == [41, 41, 45]
    final, stages, _ = suite
    assert final["output_labels"] == ["layer0_final"]
    _same_half(final["expected"][0], full_features[:, :, :16])
    _same_half(_outputs(stages)["layer0_final"], final["expected"][0])
    for item in suite:
        assert item["emit_options"] == {"fp16_reductions": "matmul", "fp16_row_mul": "compact"}
        for key, array in item["weights"].items():
            _same_half(array, supplied_weights[key])
        actual = evaluate(item["graph"], item["inputs"], item.get("weights"))
        for got, expected in zip(actual, item["expected"]):
            _same_half(got, expected)
        assert len(item["graph"].outputs) == len(item["expected"]) == len(item["tolerances"])
    assert pickle.dumps(case["graphs"]) == before
    rebuilt = build_pair(case["plan"]["target_config"], case["plan"]["draft_config"], 8,
                         gdn_indexed_copy="gather")
    assert pickle.dumps(rebuilt) == before
    assert len(rebuilt[0].outputs) == 2 and len(rebuilt[1].outputs) == 1


def test_stages_are_actual_first_layer_values_and_keep_fp16_arithmetic_boundaries(case):
    suite, _ = _suite(case)
    stages = suite[1]
    assert stages["output_labels"] == ["layer0_final", "input_norm", "chunk_core", "norm_input", "norm_gain",
                                        "gated_core", "attention_branch"]
    values = _outputs(stages)
    full = case["graphs"][0]
    full_values = _full_target_stages(full)
    full.outputs = [full_values[label] for label in stages["output_labels"]]
    for actual, expected in zip(stages["expected"], evaluate(full, _feeds(), _weights(case))):
        _same_half(actual, expected)
    # Derive independent arithmetic checks from tensor values and supplied
    # parameter files, without relying on the probe's expected-array builder.
    core = values["chunk_core"]
    square = np.square(core.astype(np.float32)).astype(np.float16)
    mean = np.mean(square.astype(np.float32), axis=-1, keepdims=True).astype(np.float16)
    norm_input = (mean.astype(np.float32) + np.float32(case["plan"]["target_config"]["rms_norm_eps"])).astype(np.float16)
    _same_half(values["norm_input"], norm_input)
    gain = (1.0 / np.sqrt(norm_input.astype(np.float32))).astype(np.float16)
    _same_half(values["norm_gain"], gain)
    weights = _weights(case)
    ids = _feeds()["input_ids"]
    embedding = weights["target.embed_tokens.weight"][ids]
    norm_square = np.square(embedding.astype(np.float32)).astype(np.float16)
    norm_mean = np.mean(norm_square.astype(np.float32), axis=-1, keepdims=True).astype(np.float16)
    denominator = (norm_mean.astype(np.float32) + np.float32(case["plan"]["target_config"]["rms_norm_eps"])).astype(np.float16)
    input_gain = (1.0 / np.sqrt(denominator.astype(np.float32))).astype(np.float16)
    normalized = (embedding.astype(np.float32) * input_gain.astype(np.float32)).astype(np.float16)
    gamma = (weights["target.layers.0.input_layernorm.weight"].astype(np.float32) + np.float32(1)).astype(np.float16)
    normalized = (normalized.astype(np.float32) * gamma.astype(np.float32)).astype(np.float16)
    _same_half(values["input_norm"], normalized)
    z = (normalized.astype(np.float32) @ weights["target.layers.0.linear_attn.in_proj_z.weight"].astype(np.float32).T).astype(np.float16)
    z = z.reshape(1, 8, 2, 8).astype(np.float32)
    silu_z = (z / (1 + np.exp(-z))).astype(np.float16)
    core_normalized = (core.astype(np.float32) * gain.astype(np.float32)).astype(np.float16)
    core_normalized = (core_normalized.astype(np.float32) * weights["target.layers.0.linear_attn.norm.weight"].astype(np.float32)).astype(np.float16)
    gated = (core_normalized.astype(np.float32) * silu_z.astype(np.float32)).astype(np.float16)
    _same_half(values["gated_core"], gated)
    branch = (gated.reshape(1, 8, 16).astype(np.float32) @ weights["target.layers.0.linear_attn.out_proj.weight"].astype(np.float32).T).astype(np.float16)
    _same_half(values["attention_branch"], branch)


def test_rsqrt_inputs_preserve_actual_subnormals_and_have_positive_normal_control(case):
    suite, _ = _suite(case)
    stages, rsqrt = suite[1:]
    assert rsqrt["output_labels"] == ["actual_norm_gain", "control_norm_gain"]
    assert set(rsqrt["inputs"]) == {"actual_norm_input", "normal_control"}
    assert {value.name for value in rsqrt["graph"].inputs} == set(rsqrt["inputs"])
    assert not rsqrt["weights"]
    actual, control = (rsqrt["inputs"][key] for key in ("actual_norm_input", "normal_control"))
    assert actual.shape == control.shape == (1, 8, 2, 1)
    _same_half(actual, _outputs(stages)["norm_input"])
    assert np.all((actual > 0) & (actual < np.finfo(np.float16).tiny))
    assert np.all(np.isfinite(control)) and np.all(control >= np.finfo(np.float16).tiny)
    for source, expected in zip((actual, control), rsqrt["expected"]):
        assert np.all(np.isfinite(expected)) and np.all(expected > 0)
        independent = (1.0 / np.sqrt(source.astype(np.float64))).astype(np.float16)
        _same_half(expected, independent)
    assert np.all(rsqrt["expected"][0] > 500)
    for key in case["plan"]["weights"]:
        item = case["plan"]["weights"][key]
        assert sha256_file(case["prepared"] / item["path"]) == item["sha256"]


@pytest.mark.parametrize("fault", [
    "prepared_weight", "prepared_identity", "prepared_config", "prepared_sequence", "prepared_quantization",
    "reference_hash", "reference_source", "reference_prompt", "reference_precision", "reference_generation",
    "omc_payload", "omc_payload_hash", "omc_source", "omc_config", "omc_abi", "omc_policy", "omc_status",
    "omc_ddk", "omc_compiler_hash", "omc_runtime", "omc_reduction_summary", "omc_row_summary", "omc_gdn_summary",
])
def test_rejects_mutated_inputs_without_generating_artifacts(case, fault):
    if fault == "prepared_weight":
        path = case["prepared"] / next(iter(case["plan"]["weights"].values()))["path"]
        path.write_bytes(path.read_bytes() + b"\x00")
    elif fault.startswith("prepared_"):
        key, value = {"prepared_identity": ("source", {**case["plan"]["source"], "fp16_payload_sha256": "0" * 64}),
                      "prepared_config": ("target_config", {**case["plan"]["target_config"], "hidden_size": 32}),
                      "prepared_sequence": ("sequence_length", 16),
                      "prepared_quantization": ("quantization", {"bits": 4})}[fault]
        case["plan"][key] = value
        _json(case["prepared"] / "prepared.json", case["plan"])
    elif fault.startswith("reference_"):
        key, value = {"reference_hash": ("prepared_manifest_sha256", "0" * 64),
                      "reference_source": ("source", {**case["reference"]["source"], "seed": 18}),
                      "reference_prompt": ("prompt_token_ids", [1, 2, 64]),
                      "reference_precision": ("precision", "torch.float32"),
                      "reference_generation": ("dflash", {"token_ids": [1, 2, 3, 4], "stop_reason": "length"})}[fault]
        case["reference"][key] = value
        _json(case["reference_path"], case["reference"])
    elif fault == "omc_payload":
        path = case["omc"] / "target.omc"
        path.write_bytes(path.read_bytes() + b"\x00")
    else:
        if fault == "omc_payload_hash":
            case["manifest"]["graphs"][0]["payloads"][0]["sha256"] = "0" * 64
        elif fault == "omc_abi":
            case["manifest"]["graphs"][0]["output_dtypes"][1] = "torch.float32"
        elif fault.endswith("_summary"):
            key = {"omc_reduction_summary": "reduction_lowering", "omc_row_summary": "row_mul_lowering",
                   "omc_gdn_summary": "gdn_copy_lowering"}[fault]
            case["manifest"]["graphs"][0][key] = {"mode": "native"}
        else:
            key, value = {"omc_source": ("source", {**case["manifest"]["source"], "seed": 18}),
                          "omc_config": ("feature_width", 16), "omc_policy": ("fp16_reductions", "unsupported"),
                          "omc_status": ("status", "FAILED"), "omc_ddk": ("ddk_id", " "),
                          "omc_compiler_hash": ("omg_sha256", "bad-hash"),
                          "omc_runtime": ("runtime", "nnrt")}[fault]
            case["manifest"][key] = value
        _json(case["omc"] / "manifest.json", case["manifest"])
    files_before = {str(p.relative_to(case["root"])): sha256_file(p) for p in case["root"].rglob("*") if p.is_file()}
    with pytest.raises(ValueError):
        _suite(case)
    files_after = {str(p.relative_to(case["root"])): sha256_file(p) for p in case["root"].rglob("*") if p.is_file()}
    assert files_after == files_before
